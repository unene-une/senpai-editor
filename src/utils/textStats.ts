// テキストの文字数を数えるためのユーティリティ。
// React に依存しない純粋な関数のみを置く。

/**
 * 改行・空白を除いた「実文字数」を数える。
 *
 * 小説投稿サイト（なろう・pixiv）や同人誌の入稿では、原稿の総文字数として
 * 改行やスペースを含めない「本文の文字数」を基準にすることが多い。
 * 一方 `content.length` は改行やスペースもそのまま1文字として数えてしまい、
 * これらのサイト・入稿基準の字数と一致しない。
 *
 * この関数では以下を除外して数える:
 * - 改行 (`\n`, `\r`)
 * - タブ (`\t`)
 * - 半角スペース、全角スペース（`　`）
 * - その他の Unicode 空白文字（`/\s/u` にマッチするもの）
 *
 * サロゲートペア（絵文字など）を1文字として正しく数えるため、
 * `for...of` でコードポイント単位に走査する。
 */
export function countPureChars(text: string): number {
  let count = 0;
  for (const ch of text) {
    if (ch === '\n' || ch === '\r' || ch === '\t' || ch === ' ' || ch === '　') continue;
    if (/\s/u.test(ch)) continue;
    count += 1;
  }
  return count;
}
